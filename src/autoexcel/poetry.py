SOLAR_TERM_DATES = {
    (3, 5): "惊蛰",
    (4, 5): "清明",
    (5, 5): "立夏",
    (5, 21): "小满",
    (6, 21): "夏至",
    (8, 7): "立秋",
    (9, 7): "白露",
    (10, 8): "寒露",
    (10, 23): "霜降",
    (11, 22): "小雪",
    (12, 22): "冬至",
}


def poetry_context(moment: datetime) -> str:
    current_date = moment.date()
    for (month, day), tag in SOLAR_TERM_DATES.items():
        term_date = date(current_date.year, month, day)
        if abs((current_date - term_date).days) <= 1:
            return tag

    hour = moment.hour
    if 5 <= hour < 9:
        return "清晨"
    if 17 <= hour < 20:
        return "黄昏"
    if hour >= 20 or hour < 5:
        return "夜晚"
    if 3 <= current_date.month <= 5:
        return "春天"
    if 6 <= current_date.month <= 8:
        return "夏天"
    if 9 <= current_date.month <= 11:
        return "秋天"
    if current_date.month in {12, 1, 2}:
        return "冬天"
    return "日常"


def poetry_line_for(moment: datetime | None = None) -> str:
    current = moment or datetime.now()
    context = poetry_context(current)
    candidates = POETRY_BY_TAG.get(context, POETRY_BY_TAG["日常"])
    context_offset = sum(ord(character) for character in context)
    index = (current.date().toordinal() + context_offset) % len(candidates)
    return candidates[index]
